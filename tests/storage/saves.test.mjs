import 'fake-indexeddb/auto';
import assert from 'node:assert/strict';
import { SaveStore } from '../../src/storage/save-store.js';
import { validateBackup } from '../../src/storage/save-schema.js';

const store = new SaveStore();
await store.open();
assert.equal((await store.profile()).stats.runsCompleted,0);
await store.updateProfile(p=>{p.progression.currency=7;p.settings.audioVolume=0.4;});
assert.equal((await store.profile()).progression.currency,7);
assert.equal((await store.profile()).settings.audioVolume,0.4);
const checkpoint = {id:'test-run-1',durationMs:1234,kills:2,scene:{player:{x:100,y:100},facing:{x:0,y:-1},weapons:[{id:'basic-laser',elapsedMs:200}],enemies:[],spawnElapsedMs:100}};
await store.saveCheckpoint(checkpoint);
assert.deepEqual(await store.checkpoint(),checkpoint);
store.db.close();
await store.open();
assert.deepEqual(await store.checkpoint(),checkpoint,'checkpoint survives reopening');
const run = {id:checkpoint.id,durationMs:2000,kills:3};
await Promise.all([store.finalizeRun(run),store.finalizeRun(run)]);
assert.deepEqual((await store.profile()).stats,{runsCompleted:1,totalKills:3,totalPlayTimeMs:2000,longestRunMs:2000});
assert.equal(await store.checkpoint(),null);
await store.saveCheckpoint(checkpoint);
assert.equal(await store.checkpoint(),null,'stale checkpoint cannot resurrect completed run');
const backup=await store.exportBackup();
validateBackup(backup);
assert.equal(backup.runs.length,1);
assert.throws(()=>validateBackup({...backup,schemaVersion:999}));
const invalid=structuredClone(backup);invalid.profile.stats.totalKills=-1;
await assert.rejects(async()=>store.importBackup(invalid));
assert.equal((await store.profile()).stats.totalKills,3,'invalid import preserves save');
await store.importBackup(backup);
assert.deepEqual(await store.profile(),backup.profile);
const failing=store.transaction(['profile'],tx=>{tx.objectStore('profile').put({broken:true},'player');throw Error('test interruption');});
await assert.rejects(failing);
assert.deepEqual(await store.profile(),backup.profile,'failed transaction rolls back');
store.db.close();
console.log('Passed: reopen persistence, checkpoint, idempotent run totals, stale checkpoint prevention, backup round trip, validation, and rollback.');
