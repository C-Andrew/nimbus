import assert from 'node:assert/strict';
import { chasePlayer, ENEMY_BEHAVIORS } from '../../src/game/enemies/enemy-behaviors.js';
const enemy = { x: -100, y: -100 };
const player = { x: 200, y: 300 };
chasePlayer(enemy, player, 100, 1000);
assert.deepEqual(enemy, { x: -40, y: -20 });
chasePlayer(enemy, { x: -40, y: 80 }, 100, 1000);
assert.deepEqual(enemy, { x: -40, y: 80 }, 'retarget each update');
chasePlayer(enemy, { x: -39, y: 80 }, 100, 1000);
assert.deepEqual(enemy, { x: -39, y: 80 }, 'never overshoot');
chasePlayer(enemy, enemy, 100, 1000);
assert(Number.isFinite(enemy.x) && Number.isFinite(enemy.y));
const a={x:0,y:0}, b={x:0,y:0}, target={x:1000,y:1000};
chasePlayer(a,target,90,1000);
for(let i=0;i<60;i++)chasePlayer(b,target,90,1000/60);
assert(Math.hypot(a.x-b.x,a.y-b.y)<1e-9,'frame-independent movement');
ENEMY_BEHAVIORS.stationary(a,target,90,1000);
assert(Math.hypot(a.x-b.x,a.y-b.y)<1e-9);
console.log('Passed: chase direction, retargeting, overshoot, coincident positions, frame independence, stationary behavior.');
