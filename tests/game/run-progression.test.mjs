import assert from 'node:assert/strict';
import { RunProgression, isValidRunProgression } from '../../src/game/run/run-progression.js';
const p = new RunProgression(100);
assert.deepEqual(p.snapshot(),{currentXp:0,totalXp:0,level:0,xpPerLevel:100});
assert.equal(p.addXp(99),0);
assert.equal(p.addXp(1),1);
assert.deepEqual(p.snapshot(),{currentXp:0,totalXp:100,level:1,xpPerLevel:100});
assert.equal(p.addXp(250),2);
assert.deepEqual(p.snapshot(),{currentXp:50,totalXp:350,level:3,xpPerLevel:100});
const restored = new RunProgression(100);
restored.restore(p.snapshot());
assert.deepEqual(restored.snapshot(),p.snapshot());
assert(!isValidRunProgression({...p.snapshot(),level:10}));
assert.throws(()=>p.addXp(-1));
assert.throws(()=>p.addXp(0.5));
assert.throws(()=>p.addXp(Number.MAX_SAFE_INTEGER));
assert.equal(p.totalXp,350,'invalid awards leave state unchanged');
assert.throws(()=>new RunProgression(0));
assert.throws(()=>new RunProgression(200).restore(p.snapshot()));
p.reset();
assert.equal(p.totalXp,0);
assert.equal(p.level,0);
restored.restore(undefined);
assert.equal(restored.totalXp,0);
console.log('Passed: XP thresholds, overflow, total tracking, restore, reset, invalid awards, and consistency validation.');

const changes = [];
const live = new RunProgression(100, value => changes.push(value));
live.addXp(5);
live.addXp(95);
assert.deepEqual(changes.at(-1), {currentXp:0,totalXp:100,level:1,xpPerLevel:100});
assert.equal(changes.length,3, 'initial state and each award notify the HUD');
live.addXp(0);
assert.equal(changes.length,3, 'zero award does not redraw');
live.reset();
assert.equal(changes.at(-1).totalXp,0);
live.restore({currentXp:50,totalXp:250,level:2,xpPerLevel:100});
assert.equal(changes.at(-1).level,2, 'recovery immediately notifies the HUD');
console.log('Passed: immediate progression display notifications for awards, level-ups, resets, and restore.');
